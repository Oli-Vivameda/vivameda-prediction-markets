NAMES={'btc':'Bitcoin','eth':'Ethereum','sol':'Solana'}

def get(url):
    parsed=urllib.parse.urlsplit(url)
    if parsed.scheme!='https' or parsed.netloc not in ('gamma-api.polymarket.com','clob.polymarket.com'):
        raise ValueError('unsupported_public_endpoint')
    req=urllib.request.Request(url,headers={'User-Agent':'VivamedaResearch/1.0','Accept':'application/json'})
    with urllib.request.urlopen(req,timeout=5) as r:raw=r.read(1048577)
    if len(raw)>1048576:raise ValueError('oversized_public_response')
    return json.loads(raw)

def epoch(value):return datetime.fromisoformat(value.replace('Z','+00:00')).timestamp()
def iso(value):return datetime.fromtimestamp(value,timezone.utc).isoformat()
def unpack(value):return json.loads(value) if isinstance(value,str) else value

def rules(raw,asset,start,received):
    if asset not in NAMES or type(start) is not int or start%300:raise ValueError('invalid_window')
    slug=asset+'-updown-5m-'+str(start)
    if raw.get('slug')!=slug or epoch(raw['endDate'])!=start+300 or epoch(raw['eventStartTime'])!=start:
        raise ValueError('window_mismatch')
    condition=raw.get('conditionId','')
    if not re.fullmatch(r'0x[0-9a-fA-F]{64}',condition):raise ValueError('invalid_condition')
    labels=unpack(raw['outcomes']);version=raw.get('version')
    if version not in ('v1','v2'):raise ValueError('unknown_market_version')
    ids=unpack(raw.get('positionIds') if version=='v2' else raw.get('clobTokenIds'))
    if (not isinstance(labels,list) or len(labels)!=2 or set(labels)!={'Up','Down'}
        or not isinstance(ids,list) or len(ids)!=2 or len(set(map(str,ids)))!=2
        or any(not re.fullmatch(r'[0-9]{1,100}',str(x)) for x in ids)):raise ValueError('invalid_outcome_mapping')
    source='https://data.chain.link/streams/'+asset+'-usd-twap-60s-streams'
    description=(f'This market will resolve to "Up" if the time-weighted average price (TWAP) of {NAMES[asset]}, generated by Chainlink, of the time range specified in the title is greater than or equal to the price at the beginning of that range. Otherwise, it will resolve to "Down".\n'
        f'The resolution source for this market is information from Chainlink, specifically the {asset.upper()}/USD TWAP data stream available at {source}.\n'
        f'Please note that this market is about the price according to the TWAP Chainlink data stream for the asset pair {asset.upper()}/USD, not according to any other sources or spot markets.')
    cfg=raw.get('cryptoMarketConfig',{})
    if (raw.get('description')!=description or raw.get('resolutionSource')!=source
        or cfg.get('asset')!=asset or cfg.get('duration')!='5m' or cfg.get('twapEnabled') is not True
        or cfg.get('twapLookbackSeconds')!=60 or raw.get('fallbackResolutionType')!='none'
        or raw.get('negRisk') is not False):raise ValueError('unrecognized_settlement_rules')
    events=raw.get('events',[])
    if len(events)!=1 or events[0].get('slug')!=slug or not str(events[0].get('id','')).isdigit():raise ValueError('event_identity')
    fees=raw.get('feeSchedule')
    if raw.get('feesEnabled') is False:rate=D(0)
    elif raw.get('feesEnabled') is True and isinstance(fees,dict) and fees.get('exponent')==1 and not isinstance(fees.get('exponent'),bool) and fees.get('takerOnly') is True:
        rate=number(fees['rate'])
    else:raise ValueError('unsupported_fee_schedule')
    tick=number(raw['orderPriceMinTickSize']);minimum=number(raw['orderMinSize'])
    if not 0<tick<1 or minimum<=0 or not 0<=rate<=1:raise ValueError('invalid_fee_or_minimum')
    return {'asset':asset,'market_id':str(raw['id']),'event_id':str(events[0]['id']),'condition':condition,'slug':slug,
        'start':start,'end':start+300,'start_utc':iso(start),'end_utc':iso(start+300),'version':version,
        'tokens':dict(zip(labels,map(str,ids))),'description':description,'rules_sha256':hashlib.sha256(description.encode()).hexdigest(),
        'source':source,'twap_seconds':60,'opening_method':'Chainlink TWAP at window start','tie':'Up','fallback':'none',
        'rate':str(rate),'tick':str(tick),'minimum_notional':str(minimum),'fee_schedule':fees,
        'retrieved_at':received,'active':raw.get('active') is True,'closed':raw.get('closed') is True,
        'accepting':raw.get('acceptingOrders') is True,'rules_verified':True}

def discover(asset,start):
    slug=asset+'-updown-5m-'+str(start);raw=get('https://gamma-api.polymarket.com/markets/slug/'+slug)
    return raw,rules(raw,asset,start,time.time())

def stamp(value):
    t=float(number(value));return t/1000 if t>1e11 else t

def book(raw,token,condition,received,generation=0,sequence=None,allow_empty=False,check_age=True):
    """check_age=False is only for ordered stream reconstruction; freshness is then enforced at use time."""
    if raw.get('asset_id')!=token or raw.get('market')!=condition:raise ValueError('wrong_book_identity')
    source=stamp(raw['timestamp'])
    if check_age and not -1<=received-source<=3:raise ValueError('stale_book')
    out={'token':token,'condition':condition,'source_at':source,'received_at':received,'generation':generation,
         'sequence':sequence,'min_shares':str(number(raw['min_order_size'])),'tick':str(number(raw['tick_size']))}
    if not 0<number(out['tick'])<1:raise ValueError('unknown_book_tick')
    for side in ('bids','asks'):
        levels={}
        for row in raw[side]:
            p,n=number(row['price']),number(row['size'])
            if not 0<p<1 or n<0 or p%number(out['tick']):raise ValueError('invalid_book_level')
            if format(p.normalize(),'f') in levels:raise ValueError('duplicate_book_level')
            levels[format(p.normalize(),'f')]=str(n)
        out[side]=[[p,n] for p,n in sorted(levels.items(),key=lambda x:number(x[0]),reverse=side=='bids') if number(n)>0]
    if number(out['min_shares'])<=0:raise ValueError('unknown_minimum')
    if not allow_empty and (not out['bids'] or not out['asks']):raise ValueError('empty_book')
    if out['bids'] and out['asks'] and number(out['bids'][0][0])>number(out['asks'][0][0]):raise ValueError('crossed_book')
    out['snapshot_id']=digest(out)
    return out

def healthy(b,m,now,c):
    if not b['bids'] or not b['asks']:raise ValueError('empty_book_no_executable_quote')
    if b['condition']!=m['condition'] or b['token'] not in m['tokens'].values():raise ValueError('stale_or_changed_book')
    if number(b['bids'][0][0])>=number(b['asks'][0][0]):raise ValueError('crossed_or_locked_book')
    if 'confirmed_at' in b:
        # v3 stream book: unchanged since its last change, proven by a live, ordered, unbroken connection.
        # The venue stream itself must not lag, and nothing may come from the future.
        if (not 0<=now-b['confirmed_at']<=c['book_liveness_seconds'] or not b['received_at']<=b['confirmed_at']
            or not -1<=b['stream_lag']<=c['feed_max_age_seconds'] or now-b['source_at']< -1):raise ValueError('stale_or_changed_book')
    elif not 0<=now-b['received_at']<=c['feed_max_age_seconds'] or not -1<=now-b['source_at']<=c['feed_max_age_seconds']:
        raise ValueError('stale_or_changed_book')
    if number(b['asks'][0][0])-number(b['bids'][0][0])>number(c['maximum_spread']):raise ValueError('spread_limit')

def execute_depth(b,m,budget,quantity=None,consumed=None,limit=None,additional='0.003',check_minimum=True):
    """Marketable BUY, visible depth only; bounded partial fills, no spread double count."""
    budget=number(budget);wanted=number(quantity) if quantity is not None else None
    if budget<=0 or (wanted is not None and wanted<=0):raise ValueError('invalid_order_size')
    used=[];principal=D(0);fee_raw=D(0);extra=D(0);shares=D(0);rate=number(m['rate']);additional=number(additional)
    for price,size in b['asks']:
        p=number(price)
        if limit is not None and p>number(limit):break
        already=number((consumed or {}).get((m['condition'],b['token'],format(p.normalize(),'f')),0))
        size=max(D(0),number(size)-already);per_fee=rate*p*(1-p);unit=p+per_fee+additional
        n=min(size,max(D(0),budget-principal-fee_raw-extra)/unit)
        if wanted is not None:n=min(n,max(D(0),wanted-shares))
        n=n.quantize(Q,rounding=ROUND_DOWN)
        if n>0:
            used.append([format(p.normalize(),'f'),str(n)]);shares+=n;principal+=p*n;fee_raw+=per_fee*n;extra+=additional*n
    fees=fee_raw.quantize(F,rounding=ROUND_CEILING);extra=extra.quantize(F,rounding=ROUND_CEILING)
    # Remove microshares until conservative fee rounding fits the all-in reservation.
    while used and principal+fees+extra>budget:
        p,n=map(number,used[-1]);unit=p+rate*p*(1-p)+additional
        trim=min(n,max(Q,((principal+fees+extra-budget)/unit).quantize(Q,rounding=ROUND_CEILING)))
        n-=trim;shares-=trim;principal-=p*trim;fee_raw-=rate*p*(1-p)*trim
        if n:used[-1][1]=str(n)
        else:used.pop()
        fees=fee_raw.quantize(F,rounding=ROUND_CEILING);extra=(additional*shares).quantize(F,rounding=ROUND_CEILING)
    if shares<=0:return {'shares':'0','principal':'0','fees':'0','additional':'0','total':'0','levels':[],'partial':True}
    if check_minimum and (principal<number(m['minimum_notional']) or shares<number(b['min_shares'])):raise ValueError('below_market_minimum')
    return {'shares':str(shares),'principal':str(principal),'fees':str(fees),'additional':str(extra),
        'total':str(principal+fees+extra),'unit_cost':str((principal+fees+extra)/shares),'levels':used,
        'partial':shares<wanted if wanted is not None else principal+fees+extra<budget-D('.0001')}

def resolution(m):
    raw=get('https://clob.polymarket.com/markets/'+m['condition'])
    tokens=raw.get('tokens',[]);winners=[t for t in tokens if t.get('winner') is True]
    if (raw.get('condition_id')!=m['condition'] or {t.get('outcome'):str(t.get('token_id')) for t in tokens}!=m['tokens']):
        raise ValueError('resolution_identity')
    if raw.get('closed') is not True or len(winners)!=1:return None
    winner=winners[0].get('outcome')
    if winner not in ('Up','Down'):raise ValueError('resolution_winner')
    return {'winner':winner,'confirmed_at':time.time(),'redeemable_observed':True,'source':'CLOB explicit winner; docs state redeemable after resolution','raw':raw}
