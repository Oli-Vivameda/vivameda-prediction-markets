def raw_market(asset='btc',start=900):
    name=market.NAMES[asset];source='https://data.chain.link/streams/'+asset+'-usd-twap-60s-streams'
    description=(f'This market will resolve to "Up" if the time-weighted average price (TWAP) of {name}, generated by Chainlink, of the time range specified in the title is greater than or equal to the price at the beginning of that range. Otherwise, it will resolve to "Down".\n'
        f'The resolution source for this market is information from Chainlink, specifically the {asset.upper()}/USD TWAP data stream available at {source}.\n'
        f'Please note that this market is about the price according to the TWAP Chainlink data stream for the asset pair {asset.upper()}/USD, not according to any other sources or spot markets.')
    slug=asset+'-updown-5m-'+str(start)
    return {'id':'1','slug':slug,'conditionId':'0x'+{'btc':'a','eth':'b','sol':'c'}[asset]*64,
        'description':description,'resolutionSource':source,'eventStartTime':market.iso(start),'endDate':market.iso(start+300),
        'outcomes':['Up','Down'],'clobTokenIds':['1','2'],'version':'v1','events':[{'id':'2','slug':slug}],
        'cryptoMarketConfig':{'asset':asset,'duration':'5m','twapEnabled':True,'twapLookbackSeconds':60},
        'fallbackResolutionType':'none','negRisk':False,'orderMinSize':5,'orderPriceMinTickSize':.01,
        'feesEnabled':True,'feeSchedule':{'rate':.07,'exponent':1,'takerOnly':True},'active':True,'closed':False,'acceptingOrders':True}


def metadata(asset='btc',start=900,now=1000):return market.rules(raw_market(asset,start),asset,start,now)
def raw_book(m,side='Up',now=1000,ask='.46',size='100'):
    return {'asset_id':m['tokens'][side],'market':m['condition'],'timestamp':now,'min_order_size':'5','tick_size':m['tick'],
        'bids':[{'price':str(number(ask)-number(m['tick'])),'size':'100'}],'asks':[{'price':ask,'size':size}]}
def books(m=None,now=1000,ask='.46',size='100'):
    m=m or metadata()
    return {s:market.book(raw_book(m,s,now,ask,size),m['tokens'][s],m['condition'],now,3) for s in ('Up','Down')}
def prediction(now=1000,p=.8):return {'p_up':p,'version':'final-minute-partial-twap.v1','observed_at':now,'calibrated':False}

def proof(m,when=1201,winner='Up'):
    return {'confirmed_at':when,'redeemable_observed':True,'winner':winner,'raw':{'condition_id':m['condition'],'closed':True,
        'tokens':[{'outcome':s,'token_id':t,'winner':s==winner} for s,t in m['tokens'].items()]}}


